(ns datahike.test.pg-datetime-series-test
  "`generate_series` over timestamps, `OVERLAPS`, and date / timestamp
   values passing through a derived table, gated against a corpus
   captured from a real PostgreSQL 17 under America/New_York.

   generate_series(ts, ts, interval) answered no rows in the select list
   and was refused in FROM; OVERLAPS did not translate at all; and any
   derived table holding a date or timestamp -- `(SELECT current_date AS
   a) v` -- failed with `invalid input syntax for column \"a\"`, because
   the column's storage takes a java.util.Date and the value was a
   LocalDate.

   The corpus is READ, not transcribed:
   `test/resources/datetime_series_corpus.edn` was generated by running
   each expression on PG 17."
  (:require [clojure.test :refer [deftest is]]
            [clojure.edn :as edn]
            [clojure.string :as str]
            [datahike.api :as d]
            [datahike.pg.server :as pg])
  (:import [datahike.pg PgWireServer$QueryHandler PgWireServer$QueryResult]))

(def ^:private corpus
  (edn/read-string (slurp "test/resources/datetime_series_corpus.edn")))

(defn- with-handler [f]
  (let [cfg {:store {:backend :memory :id (java.util.UUID/randomUUID)}
             :max-string-length 0 :schema-flexibility :write :keep-history? false}]
    (d/create-database cfg)
    (let [conn (d/connect cfg)]
      (try (f (pg/make-query-handler conn {}))
           (finally (d/release conn) (d/delete-database cfg))))))

(defn- scalar
  "Run `SELECT <expr>` and return the rendered text, or {:error msg}."
  [^PgWireServer$QueryHandler h ^String expr]
  (let [r (.execute h (str "SELECT " expr))]
    (if (.error ^PgWireServer$QueryResult r)
      {:error (.error ^PgWireServer$QueryResult r)}
      (let [rows (.rows ^PgWireServer$QueryResult r)]
        (if (zero? (alength rows))
          {:error "no rows"}
          (aget ^"[Ljava.lang.String;" (aget rows 0) 0))))))

(deftest the-corpus-agrees-with-postgresql
  (is (<= 25 (count corpus)) "the corpus is actually loaded")
  (with-handler
    (fn [^PgWireServer$QueryHandler h]
      (.execute h "SET timezone = 'America/New_York'")
      (let [bad (atom [])]
        (doseq [[expr expected err] corpus]
          (let [got (scalar h expr)]
            (cond
              (some? err)
              (when-not (and (map? got) (str/includes? (str (:error got)) err))
                (swap! bad conj [expr (str "error: " err)
                                 (if (map? got) (str (:error got)) (str got))]))
              (map? got) (swap! bad conj [expr expected (str "ERROR " (:error got))])
              :else (when-not (= expected got) (swap! bad conj [expr expected got])))))
        (doseq [[expr want got] @bad]
          (println " " expr "\n    want:" want "\n    got :" got))
        (is (empty? @bad)
            (str (count @bad) " of " (count corpus) " corpus entries disagree"))))))

(deftest an-unbounded-series-stops-at-its-limit
  ;; The regression suite's own statement (timestamp.sql). PostgreSQL's
  ;; target-list SRF is value-per-call, so the LIMIT ends it after ten
  ;; rows; built eagerly, the series stepped toward java.util.Date's
  ;; limit and filled the heap -- 3.5 GB in two minutes, until the
  ;; machine ran out of memory. Unlimited, it ends where PostgreSQL's
  ;; does: `timestamp out of range` at the first value past 294276 AD.
  ;; Expected values from PostgreSQL 17.
  (with-handler
    (fn [^PgWireServer$QueryHandler h]
      (let [r (.execute h (str "select generate_series('2022-01-01 00:00'::timestamp, "
                               "'infinity'::timestamp, '1 month'::interval) limit 10"))]
        (is (nil? (.error r)))
        (is (= ["2022-01-01 00:00:00" "2022-02-01 00:00:00" "2022-03-01 00:00:00"
                "2022-04-01 00:00:00" "2022-05-01 00:00:00" "2022-06-01 00:00:00"
                "2022-07-01 00:00:00" "2022-08-01 00:00:00" "2022-09-01 00:00:00"
                "2022-10-01 00:00:00"]
               (mapv #(aget ^"[Ljava.lang.String;" % 0) (.rows r)))))
      (let [r (.execute h (str "select count(*) from (select generate_series("
                               "'290000-01-01'::timestamp, 'infinity'::timestamp, "
                               "'1 year'::interval)) s"))]
        (is (= "timestamp out of range" (.error r)))))))
