(ns datahike.test.pg-datetime-functions-test
  "The datetime constructors, `age`, `date_bin`, `timezone()`,
   `to_timestamp(double)` and `date + time`, gated against a corpus
   captured from a real PostgreSQL 17 under America/New_York.

   None of these existed: each answered `function … does not exist`.
   They are ports of date.c and timestamp.c rather than java.time
   arithmetic, because the places they differ are exactly the ones a
   test would pick: `age` keeps years and months by borrowing fields
   downward from the EARLIER argument's month (so `age('2004-02-29',
   '2003-03-31')` is 10 mons 29 days), `make_time(24, 0, 0)` is valid
   and `make_time(10, 30, 60)` is 10:31, a negative year is BC, a wall
   clock the zone skips moves forward and one it repeats takes the
   later offset, and every refusal names its fields the way the C's
   `%d-%02d-%02d` and `%02g` do.

   The corpus is READ, not transcribed:
   `test/resources/datetime_functions_corpus.edn` was generated by
   running each expression on PG 17."
  (:require [clojure.test :refer [deftest is]]
            [clojure.edn :as edn]
            [clojure.string :as str]
            [datahike.api :as d]
            [datahike.pg.server :as pg])
  (:import [datahike.pg PgWireServer$QueryHandler PgWireServer$QueryResult]))

(def ^:private corpus
  (edn/read-string (slurp "test/resources/datetime_functions_corpus.edn")))

(defn- with-handler [f]
  (let [cfg {:store {:backend :memory :id (java.util.UUID/randomUUID)}
             :max-string-length 0 :schema-flexibility :write :keep-history? false}]
    (d/create-database cfg)
    (let [conn (d/connect cfg)]
      (try (f (pg/make-query-handler conn {}))
           (finally (d/release conn) (d/delete-database cfg))))))

(defn- scalar
  "Run `SELECT <expr>` and return the rendered text, or {:error msg}."
  [^PgWireServer$QueryHandler h ^String expr]
  (let [r (.execute h (str "SELECT " expr))]
    (if (.error ^PgWireServer$QueryResult r)
      {:error (.error ^PgWireServer$QueryResult r)}
      (let [rows (.rows ^PgWireServer$QueryResult r)]
        (if (zero? (alength rows))
          {:error "no rows"}
          (aget ^"[Ljava.lang.String;" (aget rows 0) 0))))))

(deftest the-corpus-agrees-with-postgresql
  (is (<= 50 (count corpus)) "the corpus is actually loaded")
  (with-handler
    (fn [^PgWireServer$QueryHandler h]
      (.execute h "SET timezone = 'America/New_York'")
      (let [bad (atom [])]
        (doseq [[expr expected err] corpus]
          (let [got (scalar h expr)]
            (cond
              (some? err)
              (when-not (and (map? got) (str/includes? (str (:error got)) err))
                (swap! bad conj [expr (str "error: " err)
                                 (if (map? got) (str (:error got)) (str got))]))
              (map? got) (swap! bad conj [expr expected (str "ERROR " (:error got))])
              :else (when-not (= expected got) (swap! bad conj [expr expected got])))))
        (doseq [[expr want got] @bad]
          (println " " expr "\n    want:" want "\n    got :" got))
        (is (empty? @bad)
            (str (count @bad) " of " (count corpus) " corpus entries disagree"))))))
