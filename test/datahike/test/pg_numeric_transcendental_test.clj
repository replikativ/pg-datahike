(ns datahike.test.pg-numeric-transcendental-test
  "`ln`, `log`, `exp`, `power` and `sqrt` over numeric, gated against a
   corpus captured from a real PostgreSQL 17.

   Two measured failures in `numeric_big.sql`, and NEITHER was what the
   backlog first recorded. There is an arbitrary-precision numeric path
   already (`bd-ln` and friends); `sql-ln`'s `(double x)` is the
   separate float8 overload and is correct -- PostgreSQL has both
   `ln(double precision)` and `ln(numeric)`, and `pg_typeof(ln(2))` is
   double precision, so an unadorned integer belongs there.

   What was actually wrong:

   1. `estimate_ln_dweight`, which picks the RESULT SCALE, took
      `(.doubleValue v)`. 1e400 has no double, so `Math/log` gave
      Infinity and the `long` cast of `Math/log10` of that threw
      `ERROR:  Value out of range for long: Infinity` at the client --
      losing every row of the statement, including the ones whose
      logarithms were perfectly representable.
   2. `bd-ln` reduced x = m*10^k and finished with `k * ln(10)`, where
      ln(10) was a hard-coded 160-digit string. No answer could be
      accurate past that, which is precisely where the 800-decimal LN
      check diverged -- a 160-digit common prefix, not a rounding
      difference.

   The corpus is READ, not transcribed: `test/resources/numeric_corpus.edn`
   was generated by running each expression on PG 17. Hand-copied
   expectations are one of this repo's recorded leak patterns, and the
   captured text pins the result SCALE as well as the digits -- the half
   a correct kernel still gets wrong on its own. `power(2,10)` is
   `1024.0000000000000`, because 2^10 has decimal weight 3 and the rule
   keeps 16-3 = 13 places, while `power(2,100)` clamps to 0 and prints
   an exact integer."
  (:require [clojure.test :refer [deftest is testing]]
            [clojure.edn :as edn]
            [clojure.string :as str]
            [datahike.api :as d]
            [datahike.pg.server :as pg])
  (:import [datahike.pg PgWireServer$QueryHandler PgWireServer$QueryResult]))

(def ^:private corpus
  (edn/read-string (slurp "test/resources/numeric_corpus.edn")))

(defn- with-handler [f]
  (let [cfg {:store {:backend :memory :id (java.util.UUID/randomUUID)}
             :max-string-length 0 :schema-flexibility :write :keep-history? false}]
    (d/create-database cfg)
    (let [conn (d/connect cfg)]
      (try (f (pg/make-query-handler conn {}))
           (finally (d/release conn) (d/delete-database cfg))))))

(defn- scalar
  "Run `SELECT <expr>` and return the rendered text, or {:error msg}."
  [^PgWireServer$QueryHandler h ^String expr]
  (let [r (.execute h (str "SELECT " expr))]
    (if (.error ^PgWireServer$QueryResult r)
      {:error (.error ^PgWireServer$QueryResult r)
       :sqlstate (.sqlstate ^PgWireServer$QueryResult r)}
      (let [rows (.rows ^PgWireServer$QueryResult r)]
        (if (zero? (alength rows))
          {:error "no rows"}
          (aget ^"[Ljava.lang.String;" (aget rows 0) 0))))))

(deftest the-corpus-agrees-with-postgresql
  (is (<= 100 (count corpus)) "the corpus is actually loaded")
  (with-handler
    (fn [h]
      (let [bad (atom [])]
        (doseq [[expr expected err] corpus]
          (let [got (scalar h expr)]
            (cond
              ;; PostgreSQL refused it: we must refuse it too, and say
              ;; the same thing.
              (some? err)
              (when-not (and (map? got)
                             (str/includes? (str (:error got)) err))
                (swap! bad conj [expr (str "error: " err)
                                 (if (map? got) (str (:error got)) (str got))]))

              (map? got)
              (swap! bad conj [expr expected (str "ERROR " (:error got))])

              :else
              (when-not (= expected got)
                (swap! bad conj [expr expected got])))))
        (when (seq @bad)
          (println)
          (println (count @bad) "of" (count corpus) "corpus entries disagree:")
          (doseq [[expr want got] (take 20 @bad)]
            (let [cut #(let [s (str %)] (if (> (count s) 76) (str (subs s 0 76) "…") s))]
              (println " " (cut expr))
              (println "    want:" (cut want))
              (println "    got :" (cut got)))))
        (is (empty? @bad)
            (str (count @bad) " of " (count corpus) " corpus entries disagree"))))))

(deftest ln-no-longer-falls-off-the-double-cliff
  ;; The two statements `numeric_big.sql` lost in full.
  (with-handler
    (fn [h]
      (testing "above 1e308 there is no double, and the coercion leaked"
        (is (= "921.03403719761827" (scalar h "ln('1.0e400'::numeric)")))
        (is (= "2302.5850929940457" (scalar h "ln('1.0e1000'::numeric)"))))
      (testing "the scale narrows as the result widens, keeping 16 significant digits"
        ;; rscale = 16 - ln_dweight, so a WIDER logarithm prints FEWER
        ;; decimals. 230.25… has 14, 2302.58… has 13.
        (is (= "230.25850929940457" (scalar h "ln('1.0e100'::numeric)")))
        (is (= 13 (- (count "2302.5850929940457") (inc (.indexOf "2302.5850929940457" "."))))))
      (testing "an integer argument still takes the float8 overload"
        ;; pg_typeof(ln(2)) is double precision, and exp(1) differs from
        ;; exp(1.0) in the last digit because of it.
        (is (= "2.718281828459045" (scalar h "exp(1)")))
        (is (= "2.7182818284590452" (scalar h "exp(1.0)")))))))

(deftest the-800-decimal-check-is-exact
