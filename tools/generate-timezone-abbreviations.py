#!/usr/bin/env python3
"""Generate the historical offsets of PostgreSQL's dynamic abbreviations.

Usage: python3 tools/generate-timezone-abbreviations.py path/to/pg/src/timezone/data/tzdata.zi \
    > src/datahike/pg/datetime/abbreviation_offsets.edn
"""

import argparse
from pathlib import Path
import re
import struct
import subprocess
from tempfile import TemporaryDirectory


ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "src/datahike/pg/datetime/tokens.clj"
MIN_SECOND = -(1 << 63)


def tzif_header(data, offset):
    if data[offset:offset + 4] != b"TZif":
        raise ValueError("expected a TZif header")
    return struct.unpack_from(">6I", data, offset + 20)


def tzif_block_size(counts, width):
    ut, standard, leaps, times, types, names = counts
    return times * (width + 1) + types * 6 + names + leaps * (width + 4) + standard + ut


def tzif_transitions(path):
    data = path.read_bytes()
    counts = tzif_header(data, 0)
    header = 44 + tzif_block_size(counts, 4)
    _, _, _, time_count, type_count, name_count = tzif_header(data, header)
    pos = header + 44
    times = struct.unpack_from(f">{time_count}q", data, pos)
    pos += time_count * 8
    indices = data[pos:pos + time_count]
    pos += time_count
    types = [struct.unpack_from(">lBB", data, pos + 6 * i) for i in range(type_count)]
    pos += type_count * 6
    names = data[pos:pos + name_count]
    types = [(names[start:].split(b"\0", 1)[0].decode("ascii"), offset, daylight)
             for offset, daylight, start in types]

    # PostgreSQL infers the default type for times before the first
    # transition. With recent zic data this is usually type zero.
    default = 0
    if 0 in indices:
        standard = [i for i, (_, _, daylight) in enumerate(types) if not daylight]
        before_first = [i for i in standard if i < indices[0]] if types[indices[0]][2] else []
        default = before_first[-1] if before_first else (standard or [0])[0]

    return [(MIN_SECOND, *types[default]),
            *((at, *types[i]) for at, i in zip(times, indices))]


def abbreviation_offsets(transitions, abbreviation):
    changes = []
    for at, label, offset, _ in transitions:
        if label.lower() == abbreviation and (not changes or offset != changes[-1][1]):
            # With no previous occurrence PostgreSQL uses the earliest one.
            changes.append((at if changes else MIN_SECOND, offset))
    return changes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tzdata", type=Path)
    args = parser.parse_args()
    version = args.tzdata.read_text().splitlines()[0].removeprefix("# version ")
    entries = re.findall(r'"([^"\n]+)"\s+\{:type :dyntz :zone "([^"\n]+)"\}', TOKENS.read_text())
    print(f";; IANA tzdata {version}, generated by tools/generate-timezone-abbreviations.py.")
    print(";; Unix seconds and offsets east of UTC for each dynamic abbreviation.")
    print("{")
    with TemporaryDirectory() as zones:
        subprocess.run(["zic", "-b", "fat", "-d", zones, str(args.tzdata)], check=True)
        for abbreviation, zone in sorted(entries):
            offsets = abbreviation_offsets(tzif_transitions(Path(zones) / zone), abbreviation)
            if offsets:
                values = " ".join(f"[{at} {offset}]" for at, offset in offsets)
                print(f' "{abbreviation}" [{values}]')
    print("}")


if __name__ == "__main__":
    main()
